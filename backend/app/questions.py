# 方向 -> 主题池（方向专题 + 通用基础混合）
DIRECTION_TO_TOPICS = {
    "机器学习": ["机器学习", "通用基础"],
    "深度学习": ["深度学习", "机器学习"],
    "计算机视觉": ["计算机视觉", "深度学习"],
    "自然语言处理": ["自然语言处理", "深度学习"],
    "推荐系统": ["推荐系统", "机器学习"],
    "大模型": ["大模型", "深度学习"],
    "通用算法": ["机器学习", "通用基础"],
    "销售": ["销售"],
    "采销": ["采销"],
    "产品经理": ["产品经理"],
}


def pick_questions(direction: str, n: int = 6) -> list[str]:
    topics = DIRECTION_TO_TOPICS.get(direction, ["机器学习", "通用基础"])
    pool = []
    for t in topics:
        pool.extend(QUESTIONS.get(t, []))
    random.shuffle(pool)
    return pool[:n]
